// Writes base44/shared/rules.generated.ts: every table's row rules from base44/entities, for the
// backend to apply in code (base44/shared/rls.ts). Functions on Base44 can't read the schema
// files at run time, so the rules are compiled in.
//
//   node scripts/build-rules.mjs          write it
//   node scripts/build-rules.mjs --check  fail if it's out of date (run by npm test)
import fs from "node:fs";

const dir = new URL("../base44/entities/", import.meta.url);
const out = new URL("../base44/shared/rules.generated.ts", import.meta.url);
const parse = (t) => JSON.parse(t.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, ""));
const rules = {};
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".jsonc")).sort()) {
  const s = parse(fs.readFileSync(new URL(f, dir), "utf8"));
  rules[s.name] = s.rls ?? null;
}
const text = `// Generated by scripts/build-rules.mjs from base44/entities. Don't edit: change the schema files, then run it.\nexport const RULES = ${JSON.stringify(rules, null, 2)} as const;\n`;
if (process.argv.includes("--check")) {
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== text) {
    console.error("base44/shared/rules.generated.ts is out of date. Run: node scripts/build-rules.mjs");
    process.exit(1);
  }
  console.log("rules.generated.ts is up to date.");
} else {
  fs.writeFileSync(out, text);
  console.log(`Wrote base44/shared/rules.generated.ts (${Object.keys(rules).length} tables).`);
}
